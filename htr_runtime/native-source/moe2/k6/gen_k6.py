"""Generate k6.hip (K6-A routed-MoE block kernel for v0.2.4) from the byte-preserved v0.2.3 moe2 kernel body.

Every change to the served kernel is an asserted string patch, so the diff against
native-source/moe2/kernel.hip is exactly the patch list below (the same discipline htr-core used in
campaigns/htr-core-20261109/s0b/core/gen_k6b.py, from which this file is adapted).

Pipeline:
  1. extract the device code of ../kernel.hip (everything before the host section), drop torch/ATen
     includes, wrap in `namespace inc_moe`            -> inc_moe2.inc
  2. copy the k_e82_moe body out of it, apply the patches -> k6_moe<K6Args>
  3. append k6_plan (= k_moe_plan2 + optional shared-expert groups + optional sg[] gate)
                                                      -> generated/k6.hip

OPT bits (template int OPT, compile-time; the binding instantiates the adopted set only):
   1 ROWX   a group works on its real row count mr, not the launch bucket M
   4 SHX    the shared expert rides as one extra group from index A; sg[t] comes from k6_plan
   8 NOPRO  ABLATION, wrong results: prologue replaced by constant LDS fills
  16 NOEPI  ABLATION, wrong results: last arriver returns before the output transform
  32 CMB    fused combine: per token the 10 slot ids/weights, then the 10 values, loaded before the sum
  64 EPW    output transform in registers (wave = row), 16-byte nontemporal loads, k6_nofuse product
 128 EPL    output transform, LDS path, with the split count at compile time (NSC); kept for reference

Routed-expert math, layouts, launch grids (up to the group count) and counters are unchanged.
Usage: python3 native-source/moe2/k6/gen_k6.py   (rewrites inc_moe2.inc and k6.hip; prints sha256)
"""
import hashlib
import os
import re

HERE = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.join(HERE, '..', 'kernel.hip')
OUTDIR = HERE   # generated files sit beside the generator (the repo ignores **/generated/**)

# ---------------------------------------------------------------- 1. incumbent device body (unmodified)
raw = open(SRC, 'rb').read()
src_sha = hashlib.sha256(raw).hexdigest()
lines = raw.decode().splitlines()
end = next(i for i, l in enumerate(lines) if re.match(r'^// =+ host', l))
body = [l for l in lines[:end] if not re.match(r'\s*#include\s*<(torch|ATen)', l)]
incs = [l for l in body if l.startswith('#include')]
rest = [l for l in body if not l.startswith('#include')]
inc_txt = ('// GENERATED by gen_k6.py from native-source/moe2/kernel.hip (sha256 ' + src_sha + '):\n'
           '// device code, unmodified, torch includes dropped.\n#pragma once\n'
           + '\n'.join(incs) + '\nnamespace inc_moe {\n' + '\n'.join(rest) + '\n}  // namespace inc_moe\n')

# ---------------------------------------------------------------- 2. K6 kernel body
a = inc_txt.index('template <int KF, int M, int PH, int FUSE = 0>\n__global__ __launch_bounds__(256) void k_e82_moe(MoeArgs a) {')
b = inc_txt.index('// ---------------------------------------------------------------- plan: A = T*topk')
body = inc_txt[a:b].rstrip() + '\n'
# tight LDS (NBL): the served body reserves MOE_MAXB input blocks per row for every bucket; make the row stride a
# template parameter (the launch's bps decides it, the kernel traps if bps > NBL). Text-level, before any patch.
assert body.count('MOE_MAXB') == 3
body = body.replace('MOE_MAXB', 'NBL')


def patch(old, new):
    global body
    assert body.count(old) == 1, 'patch anchor not unique: ' + old[:70]
    body = body.replace(old, new)


patch('template <int KF, int M, int PH, int FUSE = 0>\n__global__ __launch_bounds__(256) void k_e82_moe(MoeArgs a) {',
      'template <int KF, int M, int PH, int FUSE, int OPT, int NBL = MOE_MAXB, int NT = 0, int NSC = 0>\n'
      '__global__ __launch_bounds__(256) void k6_moe(K6Args A6) {\n  const MoeArgs& a = A6.a;')
# SHX: a shared-expert group is admitted even when the layer's KF differs from 5 (it is a K5 matrix).
patch('  if constexpr (KF != 0) { if (K != KF) return; }',
      '  const bool shg = ((OPT & 4) != 0) && gidx >= A6.sh_g;\n'
      '  if constexpr (KF != 0) { if (K != KF && !shg) return; }')
# ROWX: prologue covers the group's real rows only (+ NOPRO ablation branch).
patch('  for (int it = w; it < M * nb; it += 8) {',
      '''  const int prow = (OPT & 1) ? mr : M;
  if constexpr ((OPT & 8) != 0) {
    for (int it = w; it < prow * nb; it += 8) {
      const int r = it / nb, bl = it % nb;
#pragma unroll
      for (int e2 = 0; e2 < 4; ++e2) xs_l[r][bl * 128 + lane * 4 + e2] = (_Float16)0.25f;
      if (lane == 0) { bscale[r][bl] = 1.f; bsum[r][bl] = 32.f; }
    }
  } else
  for (int it = w; it < prow * nb; it += 8) {''')


def cases(K):
    return ''.join(
        f'        case {r}: if constexpr (M >= {r}) tile_loop<{K}, {r}>(qm, pitch, il, b0, nb, lane, xs_l, bscale, a0, a1); break;\n'
        for r in range(1, 9))


# ROWX: one instantiation per real row count (a row's dot chain is unchanged, so per-row bits are unchanged).
patch('  if constexpr (KF != 0) {\n    tile_loop<KF, M>(',
      '  if constexpr (KF != 0 && (OPT & 1) != 0) {\n    if (shg) {\n'
      '      const size_t pitch = (size_t)nt * 40 + a.spadk[5];\n      switch (mr) {\n' + cases(5) +
      '        default: break;\n      }\n    } else {\n'
      '      const size_t pitch = (size_t)nt * 8 * KF + a.spadk[KF];\n      switch (mr) {\n' + cases('KF') +
      '        default: break;\n      }\n    }\n  } else if constexpr (KF != 0) {\n    tile_loop<KF, M>(')
patch('    for (int r = 0; r < M; ++r) {\n      float off = 0.f;',
      '    for (int r = 0; r < M; ++r) {\n      if ((OPT & 1) && r >= mr) continue;\n      float off = 0.f;')
patch('  if (!is_last) return;\n',
      '  if (!is_last) return;\n  if constexpr ((OPT & 16) != 0) { if (threadIdx.x == 0) *cnt = 0u; return; }\n')

# EPW: output transform for all rows at once in registers (wave = row), no LDS, no barriers.
old_epi = body[body.index('  for (int r = 0; r < mr; ++r) {\n    if (t < 128) {\n      float s = 0.f;'):
               body.index('  if (t == 0) *cnt = 0u;')]
assert old_epi.count('__syncthreads();') == 4
new_epi = '''  if constexpr ((OPT & 64) != 0 && NSC != 0) {
    if (w < mr) {
      const int r = w;
      k6_f4 pv[NSC ? NSC : 1];
#pragma unroll
      for (int k = 0; k < NSC; ++k) pv[k] = __builtin_nontemporal_load(reinterpret_cast<const k6_f4*>(a.part + (((size_t)gidx * NSC + k) * M + r) * m + sb * 128 + lane * 4));
      k6_f4 s4 = {0.f, 0.f, 0.f, 0.f};
#pragma unroll
      for (int k = 0; k < NSC; ++k) s4 += pv[k];
      const k6_h4 hs = *reinterpret_cast<const k6_h4*>(scl + sbl * 128 + lane * 4);
      float v[4] = {k6_nofuse(s4.x * (float)hs.x * a.cb), k6_nofuse(s4.y * (float)hs.y * a.cb), k6_nofuse(s4.z * (float)hs.z * a.cb), k6_nofuse(s4.w * (float)hs.w * a.cb)};
      fwht128_wave(v, lane);
      const unsigned sg4 = (unsigned)svp[sbl * 16 + (lane >> 1)] >> ((lane & 1) * 4);
      k6_f4 o4;
      o4.x = v[0] * (1.0f / 11.313708498984761f); o4.y = v[1] * (1.0f / 11.313708498984761f);
      o4.z = v[2] * (1.0f / 11.313708498984761f); o4.w = v[3] * (1.0f / 11.313708498984761f);
      if (sg4 & 1) o4.x = -o4.x;
      if (sg4 & 2) o4.y = -o4.y;
      if (sg4 & 4) o4.z = -o4.z;
      if (sg4 & 8) o4.w = -o4.w;
      *reinterpret_cast<k6_f4*>(a.out + ((size_t)gidx * M + r) * m + sb * 128 + lane * 4) = o4;
    }
  } else {
''' + '\n'.join(('  ' + l if l else l) for l in old_epi.rstrip('\n').split('\n')) + '\n  }\n'
patch(old_epi, new_epi)
# SHX: the fused combine adds sg[t] * shared[t] before the single bf16 rounding.
patch('          if (sl >= 0) s += a.wts[tk * a.topk + k] * a.out[(size_t)sl * MOE_H + i];\n        }\n',
      '          if (sl >= 0) s += a.wts[tk * a.topk + k] * a.out[(size_t)sl * MOE_H + i];\n        }\n'
      '        if constexpr ((OPT & 4) != 0) s += A6.sg[tk] * a.out[((size_t)A6.sh_g * M + tk) * MOE_H + i];\n')
# CMB: per token the 10 slot ids/weights, then the 10 output values, are loaded before the sum
# (served: one conditional load chain per term); tokens alternate over the two thread halves.
patch('    if (t < 128) {\n      const int i = sb * 128 + t; ', """    if constexpr ((OPT & 32) != 0) {
      if (a.topk != 10) __builtin_trap();
      const int i = sb * 128 + (t & 127);
      for (int tk = t >> 7; tk < a.T; tk += 2) {
        int sl[10]; float wv[10], ov[10];
#pragma unroll
        for (int k = 0; k < 10; ++k) { sl[k] = a.slot[tk * 10 + k]; wv[k] = a.wts[tk * 10 + k]; }
        float so = 0.f, sgv = 0.f;
        if constexpr ((OPT & 4) != 0) { so = a.out[((size_t)A6.sh_g * M + tk) * MOE_H + i]; sgv = A6.sg[tk]; }
#pragma unroll
        for (int k = 0; k < 10; ++k) ov[k] = a.out[(size_t)(sl[k] < 0 ? 0 : sl[k]) * MOE_H + i];
        float s = 0.f;
#pragma unroll
        for (int k = 0; k < 10; ++k) { const float s2 = s + wv[k] * ov[k]; s = sl[k] >= 0 ? s2 : s; }
        if constexpr ((OPT & 4) != 0) s += sgv * so;
        a.y[(size_t)tk * MOE_H + i] = __float2bfloat16(s);
      }
    } else
    if (t < 128) {
      const int i = sb * 128 + t; """)
# tight LDS (NBL) and NT: the served body reserves MOE_MAXB input blocks per row and uses nontemporal
# weight loads only at K4 x 1 row. Same code, row stride as a parameter, trap if the launch exceeds it.
ta = inc_txt.index('// trellis tile loop for one 16-row strip')
tb = inc_txt.index('__device__ __forceinline__ float silu_f(float g)')
tl = inc_txt[ta:tb]
assert tl.count('template <int K, int M>') == 1 and tl.count('MOE_MAXB') == 2 and tl.count('void tile_loop(') == 1
assert tl.count('if constexpr (K == 4 && M == 1) {') == 1
tl = tl.replace('if constexpr (K == 4 && M == 1) {', 'if constexpr ((K == 4 && M == 1) || NT != 0) {')
tl = tl.replace('template <int K, int M>', 'template <int K, int M, int NBL, int NT>').replace('MOE_MAXB', 'NBL').replace(
    'void tile_loop(', 'void tile_loop_n(')
body, n_ = re.subn(r'tile_loop<([^>]*)>\(', r'tile_loop_n<\1, NBL, NT>(', body)
assert n_ == 20, n_
patch('  const int b0 = sp * a.bps, b1 = min(n >> 7, b0 + a.bps), nb = b1 - b0;',
      '  const int b0 = sp * a.bps, b1 = min(n >> 7, b0 + a.bps), nb = b1 - b0;\n'
      '  if (a.bps > NBL) __builtin_trap();\n  if constexpr (NSC != 0) { if (ns != NSC) __builtin_trap(); }')
# EPL (reference): LDS path with the split count at compile time, partial loads issued together.
patch('        for (int k = 0; k < ns; ++k) s += __builtin_nontemporal_load(a.part + (((size_t)gidx * ns + k) * M + r) * m + row);',
      """        if constexpr ((OPT & 128) != 0 && NSC != 0) {
          float pv[NSC ? NSC : 1];
#pragma unroll
          for (int k = 0; k < NSC; ++k) pv[k] = __builtin_nontemporal_load(a.part + (((size_t)gidx * NSC + k) * M + r) * m + row);
#pragma unroll
          for (int k = 0; k < NSC; ++k) s += pv[k];
        } else
        for (int k = 0; k < ns; ++k) s += __builtin_nontemporal_load(a.part + (((size_t)gidx * ns + k) * M + r) * m + row);""")
# VP (NT 2): one 16-byte nontemporal load per lane and tile; the wrap-around word V[0] of lane q is
# V[K] of lane (q-1)&7 of the same 8-lane subgroup, taken with v_permlane16.
assert tl.count('    if constexpr ((K == 4 && M == 1) || NT != 0) {') == 1
tl = tl.replace('    if constexpr ((K == 4 && M == 1) || NT != 0) {', """    if constexpr (NT == 2 && K >= 4) {
      const k6_u4 wa = __builtin_nontemporal_load(reinterpret_cast<const k6_u4a*>(tp + q * K));
      V[1] = wa.x; V[2] = wa.y; V[3] = wa.z; V[4] = wa.w;
#pragma unroll
      for (int k = 4; k < K; ++k) V[k + 1] = __builtin_nontemporal_load(tp + q * K + k);
      V[0] = __builtin_amdgcn_permlane16(V[K], V[K], 0x65432107u, 0xedcba98fu, false, false);
    } else if constexpr ((K == 4 && M == 1) || NT != 0) {""")
body = tl + body

# k6_plan: k_moe_plan2 + SPLIT (group > M rows -> several groups of <= M) + optional shared groups + optional sg[].
# nsh is a host argument here (0 = shared expert not folded; K6-B passes ceil(T/M)).
plan = '''
// k6_plan = k_moe_plan2 (identical grp_e/grp_rows/grp_n/slot for groups < A when no expert has more than M rows)
// + SPLIT + the optional shared-expert groups from index A, ng = routed groups + shared groups, and, when nsh > 0,
// sg[t] = sigmoid(wsg . x[t]) (fp32 products, fixed reduction order). One WG of 256. nsh is a host argument so the
// K6-A build (routed only) allocates no shared group and computes no gate.
__global__ void k6_plan(const int* __restrict__ ids, int A, int topk, int M, int* __restrict__ grp_e, int* __restrict__ grp_rows,
                        int* __restrict__ grp_n, int* __restrict__ slot, int* __restrict__ ng, int T, int sh_e, int nsh,
                        const __hip_bfloat16* __restrict__ x, const __hip_bfloat16* __restrict__ wsg, float* __restrict__ sg) {
  __shared__ int s_ng;
  __shared__ float red[256];
  const int a = threadIdx.x;
  if (a == 0) s_ng = 0;
  __syncthreads();
  if (a < A) {
    const int e = ids[a];
    // SPLIT: an expert used by more than M rows becomes several groups of <= M rows (leader = every assignment whose
    // rank among the assignments of the same expert is a multiple of M). Rows are independent, so the launch bucket M
    // no longer has to cover the largest group. For <= M rows per expert this is the old plan, element for element.
    int rank = 0;
    if (e >= 0)
      for (int b = 0; b < a; ++b) rank += ids[b] == e;
    if (e < 0) { grp_e[a] = -1; grp_n[a] = 0; slot[a] = -1; }
    else if (rank % M != 0) { grp_e[a] = -1; grp_n[a] = 0; }
    else {
      int c = 0;
      for (int b = a; b < A && c < M; ++b)
        if (ids[b] == e) { grp_rows[a * M + c] = b / topk; slot[b] = a * M + c; ++c; }
      grp_e[a] = e; grp_n[a] = c;
      for (int c2 = c; c2 < M; ++c2) grp_rows[a * M + c2] = 0;
      atomicAdd(&s_ng, 1);
    }
  }
  __syncthreads();
  if (a == 0) ng[0] = s_ng + nsh;
  if (nsh == 0) return;                           // K6-A: no shared group, no gate
  // shared expert: groups A .. A+nsh-1, rows j*M .. of the T tokens
  if (a < nsh) { grp_e[A + a] = sh_e; grp_n[A + a] = min(M, T - a * M); }
  if (a < nsh * M) grp_rows[A * M + a] = a < T ? a : 0;
  for (int t = 0; t < T; ++t) {
    float p = 0.f;
    for (int i = a; i < MOE_H; i += 256) p += __bfloat162float(wsg[i]) * __bfloat162float(x[(size_t)t * MOE_H + i]);
    red[a] = p;
    __syncthreads();
    if (a < 32) {
      float q = 0.f;
      for (int k = 0; k < 8; ++k) q += red[k * 32 + a];
      q = wave_sum(q);
      if (a == 0) sg[t] = 1.0f / (1.0f + __expf(-q));
    }
    __syncthreads();
  }
}
'''
head = '''// GENERATED by gen_k6.py from native-source/moe2/kernel.hip (v0.2.3 moe2) + the asserted patches listed there.
// Do not edit; edit gen_k6.py. K6-A = ROWX + CMB + EPW + tight LDS + NT/VP + SPLIT (SHX compiled out unless OPT&4).
#pragma once
// torch/ATen first: the served kernel.hip includes them before the hip runtime headers, and k6_host.inc needs
// TORCH_CHECK / torch::Tensor / at::cuda::getCurrentCUDAStream in this translation unit.
#include <torch/extension.h>
#include <ATen/hip/HIPContext.h>
#include "inc_moe2.inc"
namespace k6a {
using namespace inc_moe;
struct K6Args { MoeArgs a; int sh_g; const float* sg; };
typedef float k6_f4 __attribute__((ext_vector_type(4)));
typedef _Float16 k6_h4 __attribute__((ext_vector_type(4)));
typedef uint32_t k6_u4 __attribute__((ext_vector_type(4)));
typedef k6_u4 k6_u4a __attribute__((aligned(4)));
__device__ __forceinline__ float k6_nofuse(float v) {
  return __builtin_bit_cast(float, __builtin_amdgcn_update_dpp(0, __builtin_bit_cast(int, v), 0xE4, 0xF, 0xF, false));
}
'''
out = head + body + plan + '}  // namespace k6a\n\n// hand-written launch/dispatch + entry points (not generated)\n#include "k6_host.inc"\n'

os.makedirs(OUTDIR, exist_ok=True)
open(os.path.join(OUTDIR, 'inc_moe2.inc'), 'w').write(inc_txt)
open(os.path.join(HERE, 'k6.hip'), 'w').write(out)
for name, txt in (('inc_moe2.inc', inc_txt), ('k6.hip', out)):
    print(name, len(txt), 'bytes', len(txt.splitlines()), 'lines',
          hashlib.sha256(txt.encode()).hexdigest()[:16])
print('source native-source/moe2/kernel.hip', src_sha)
